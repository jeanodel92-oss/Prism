let current = "en";

/** `locale`: the language "as the terminal" stands for (the engine's, or the system locale before it answers). */
export function setLanguage(preference, locale) {
	const system = (locale || navigator.language || "en").toLowerCase().startsWith("fr") ? "fr" : "en";
	current = preference === "fr" || preference === "en" ? preference : system;
	document.documentElement.lang = current;
	return current;
}

/** A count in the window's language ("12 345" in French). */
export function formatNumber(value) {
	return Number(value ?? 0).toLocaleString(current);
}

/** A cost in dollars, three decimals, in the window's language ("0,010 $" in French). */
export function formatCost(value) {
	return t("cost", Number(value ?? 0).toLocaleString(current, { minimumFractionDigits: 3, maximumFractionDigits: 3 }));
}

export function t(key, ...args) {
	const text = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
	// One pass with a function: "$&" in a path stays literal, and a "{1}" inside the first value is not filled again.
	return text.replace(/\{(\d+)\}/g, (match, i) => (Number(i) < args.length ? String(args[Number(i)]) : match));
}
