#!/usr/bin/env node
// fork: rewrites the list of pi's files in REUSE.toml, between its two markers. Everything not on that list is the
// fork's (GPL-3.0-or-later) unless a later annotation names its own licence, so a new fork file needs no entry.
// Files are listed one by one, never as a directory glob, which would also take in a fork file added there later.
//
// A tracked file is pi's when its path is in the tree of the upstream release the fork is based on, or of the
// upstream ref commits are taken from (cherry-picks). Run it after every upstream sync.
//
//   node fork/scripts/reuse-upstream.mjs [base-ref] [upstream-ref]     (defaults: v1.0.0 upstream/main)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const [base = "v1.0.0", upstream = "upstream/main"] = process.argv.slice(2);
const BEGIN = "# BEGIN pi files (generated by fork/scripts/reuse-upstream.mjs, do not edit)";
const END = "# END pi files";

const git = (...args) => execFileSync("git", args, { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
const lines = (out) => out.split("\n").filter(Boolean);
const pi = new Set([
	...lines(git("ls-tree", "-r", "--name-only", base)),
	...lines(git("ls-tree", "-r", "--name-only", upstream)),
]);
const files = lines(git("ls-files"))
	.filter((file) => pi.has(file))
	.sort();
const glob = files.find((file) => /[*?[\]\\]/.test(file));
if (glob) throw new Error(`glob character in ${glob}: escape it in REUSE.toml`);

const block = [
	BEGIN,
	"[[annotations]]",
	"path = [",
	...files.map((file) => `\t${JSON.stringify(file)},`),
	"]",
	'SPDX-FileCopyrightText = "2025 Mario Zechner"',
	'SPDX-License-Identifier = "MIT"',
	END,
].join("\n");

const toml = readFileSync("REUSE.toml", "utf8");
const start = toml.indexOf(BEGIN);
const stop = toml.indexOf(END);
if (start < 0 || stop < start) throw new Error("REUSE.toml: markers not found");
writeFileSync("REUSE.toml", toml.slice(0, start) + block + toml.slice(stop + END.length));
console.log(`${files.length} files of pi listed`);
